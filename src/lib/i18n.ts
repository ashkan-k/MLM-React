export const dictionaries = { fa, en }

let activeLocale: Locale = typeof localStorage !== 'undefined' && localStorage.getItem('finopal.locale') === 'en' ? 'en' : 'fa'

export function setActiveLocale(locale: Locale) {
  activeLocale = locale
}

export function getActiveLocale() {
  return activeLocale
}

export function translate(key: string, vars?: Record<string, string | number>, locale = activeLocale) {
  let text = dictionaries[locale][key] ?? dictionaries.fa[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

export function roleLabel(slug?: string | null, locale = activeLocale) {
  if (!slug) return '—'
  return translate(`role_${slug}`, undefined, locale)
}
